#!/usr/bin/env python3
"""Build and audit E3 ownership classes without running any search.

The paired design reuses every active L-main network.  It keeps customer
locations, demand, time windows and carbon data fixed, then compares
nearest-depot ownership with one preregistered spatially mixed portfolio.
Mixed ownership is generated by permuting the nearest-depot labels inside
service-shift and demand-quartile blocks.  Fleet adequacy is handled later by
one outcome-blind common-envelope design, so a source network is not excluded
merely because its historical metadata contains only one powertrain.
"""

